

document.addEventListener("keydown", function(event) {
    if (event.key === "ArrowRight") {
        console.log("Right")
    }
    if (event.key === "ArrowUp") {
        console.log("Up")
    }
    if (event.key === "ArrowDown") {
        console.log("Down")
    }
    if (event.key === "ArrowLeft") {
        console.log("Left")
    }



});
